#!/usr/bin/env node
/**
 * tools/extract-core.mjs
 * ---------------------------------------------------------------------------
 * 从上游 calculator.js 按「行段」逐字抽取纯计算内核，生成 src/core/calc-core.js。
 *
 * 设计原则：
 *  1. 只搬运，不改写：抽到的每一行都原样复制（含注释），保证与上游网页完全一致。
 *  2. 锚点校验：每段都有首/末行指纹，上游文件一旦漂移就立即报错退出（非 0）。
 *  3. 生成后自检：符号齐全 + vm 加载 + 真实数据跑通一次伤害计算。
 *
 * 运行：node tools/extract-core.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const UPSTREAM = path.join(ROOT, '_intermediates', 'upstream', 'calculator.js');
const OUT = path.join(ROOT, 'src', 'core', 'calc-core.js');
const DATA_DIR = path.join(ROOT, '_intermediates', 'upstream', 'datas', 'final');

/** 抽取段定义（1-based，含首尾）。expectStart/expectLast 用于锚点校验。 */
const RANGES = [
  { id: 'A', label: '元素表 / stripXi / elOf', start: 1, end: 53, expectStart: /^\/\/ =+$/, expectLast: /^\}$/ },
  { id: 'B', label: '属性键 / 性格 / 加点常量', start: 119, end: 133, expectStart: /^const STAT_KEYS/, expectLast: /^\};$/ },
  { id: 'G', label: 'getBuff（SKILL_MODS 依赖的侧向 buff 读取）', start: 867, end: 870, expectStart: /^function getBuff/, expectLast: /^\}$/ },
  { id: 'C', label: '性格/加点终值 / STAB / 相性', start: 942, end: 1020, expectStart: /^\/\/ =+$/, expectLast: /^\}$/ },
  { id: 'D', label: '特性查询 / skillMod ctx / 能耗', start: 2693, end: 2764, expectStart: /^function getSpiritAbility/, expectLast: /^\/\/ / },
  { id: 'E', label: 'SKILL_MODS 全表 / 先手表 / 动态修正', start: 3356, end: 3937, expectStart: /^function isFirstStrike/, expectLast: /^\}$/ },
  { id: 'F', label: 'computeFinalDamage', start: 3948, end: 4051, expectStart: /^function computeFinalDamage/, expectLast: /^\}$/ },
];

/** 生成文件必须包含的符号 */
const REQUIRED_SYMBOLS = [
  'computeFinalDamage', 'computeSkillDynamicModifiers', 'SKILL_MODS', 'effectiveness',
  'getFinalStat', 'buildSkillModCtx', 'getStabMultiplier', 'getNatureMultiplier',
  'getIVBonus', 'isFirstStrike', 'getSpiritAbility', 'hasSkillMod', 'isSkillModRelevant',
  'getSkillEnergy', 'getBuff', 'STAT_KEYS', 'STAT_LABELS', 'MAX_IV', 'IV_BONUS',
  'DEFAULT_NATURE', 'DEFAULT_IVS', 'ELEMENTS', 'FALLBACK_EL', 'ELEMENT_BY_RAW',
  'stripXi', 'elOf', 'SKILL_MODS_SIDES', 'FIRST_STRIKE_SKILLS', 'LAST_STRIKE_SKILLS',
];

/** 暴露给渲染层/Node 的 API */
const EXPORTS = [
  'bindData',
  'ELEMENTS', 'FALLBACK_EL', 'ELEMENT_BY_RAW', 'stripXi', 'elOf',
  'STAT_KEYS', 'STAT_LABELS', 'MAX_IV', 'IV_BONUS', 'DEFAULT_NATURE', 'DEFAULT_IVS',
  'getNatureMultiplier', 'getIVBonus', 'getFinalStat', 'getStabMultiplier', 'effectiveness',
  'getSpiritAbility', 'hasSkillMod', 'isSkillModRelevant', 'buildSkillModCtx', 'getSkillEnergy', 'getBuff',
  'isFirstStrike', 'SKILL_MODS', 'SKILL_MODS_SIDES', 'FIRST_STRIKE_SKILLS', 'LAST_STRIKE_SKILLS',
  'computeSkillDynamicModifiers', 'computeFinalDamage',
  'getState', 'setGlobalState',
];

function fail(msg) {
  console.error('[extract-core] ✗ ' + msg);
  process.exit(1);
}

// ---------------------------------------------------------------------------
// 1. 读取上游
// ---------------------------------------------------------------------------
if (!fs.existsSync(UPSTREAM)) fail('找不到上游文件：' + UPSTREAM);
const raw = fs.readFileSync(UPSTREAM, 'utf8');
const lines = raw.split(/\r?\n/);
const srcHash = crypto.createHash('sha256').update(raw).digest('hex');

// ---------------------------------------------------------------------------
// 2. 按段切片 + 锚点校验
// ---------------------------------------------------------------------------
const segments = [];
for (const r of RANGES) {
  if (r.end > lines.length) fail('段 ' + r.id + ' 越界（文件仅 ' + lines.length + ' 行）');
  const first = lines[r.start - 1];
  const last = lines[r.end - 1];
  if (!r.expectStart.test(first)) fail('段 ' + r.id + ' 起始锚点不匹配（第 ' + r.start + ' 行）：' + JSON.stringify(first));
  if (!r.expectLast.test(last)) fail('段 ' + r.id + ' 结束锚点不匹配（第 ' + r.end + ' 行）：' + JSON.stringify(last));
  const body = lines.slice(r.start - 1, r.end).join('\n');
  segments.push({ ...r, body });
}

// 记录每段被抽走了多少行，便于人工核对
const report = segments.map(s => '//   ' + s.id + ' ' + s.start + '-' + s.end + ' (' + (s.end - s.start + 1) + ' 行) ' + s.label).join('\n');

// ---------------------------------------------------------------------------
// 3. 拼装生成文件
// ---------------------------------------------------------------------------
const header = [
  '// ===========================================================================',
  '// src/core/calc-core.js  ——  自动生成，请勿手改',
  '// generated by tools/extract-core.mjs from _intermediates/upstream/calculator.js',
  '// upstream sha256: ' + srcHash,
  '// 抽取段：',
  report,
  '// ---------------------------------------------------------------------------',
  '// 说明：段 G（getBuff）不在原始清单里，但 SKILL_MODS 内部（如星际粉尘/和弦共振）',
  '// 会读取攻击方/防御方的属性 buff 百分比，缺它会在运行期抛 ReferenceError，故一并抽出。',
  '// 浮窗不使用属性 buff，shim 里把两侧 buff 固定为 0。',
  '// ===========================================================================',
  '',
  '/* eslint-disable */',
  "/* global window, module */",
  '',
  '// ===================== shim：上游的全局数据与可变状态 =====================',
  'let SPRITES = {}, SKILLS = {}, TYPES = {}, OTHERS = {};',
  'const state = {',
  '  attackerSpeed: 0, defenderSpeed: 0, attackerPowerBoost: 0, attackerCombo: 0,',
  '  // 属性 buff（百分比）：浮窗不开放该功能，固定 0；getBuff() 需要这两个对象存在。',
  '  attackerBuff: { hp: 0, atk: 0, matk: 0, def: 0, mdef: 0, spd: 0 },',
  '  defenderBuff: { hp: 0, atk: 0, matk: 0, def: 0, mdef: 0, spd: 0 },',
  '};',
  'function bindData({ sprites, skills, types, others }) {',
  '  SPRITES = sprites || {};',
  '  SKILLS = skills || {};',
  '  TYPES = types || {};',
  '  OTHERS = others || {};',
  '}',
  'function getState() { return state; }',
  '/** 只允许改速度/威力/连击三个全局修正，其余保持 0（浮窗口径） */',
  'function setGlobalState(patch) {',
  '  if (!patch) return state;',
  "  for (const k of ['attackerSpeed', 'defenderSpeed', 'attackerPowerBoost', 'attackerCombo']) {",
  '    if (typeof patch[k] === "number" && Number.isFinite(patch[k])) state[k] = patch[k];',
  '  }',
  '  return state;',
  '}',
  '',
].join('\n');

const body = segments
  .map(s => '\n// ===================== 段 ' + s.id + '：' + s.label + '（上游 ' + s.start + '-' + s.end + '）=====================\n' + s.body + '\n')
  .join('\n');

const footer = [
  '',
  '// ===================== 导出（Node require / 浏览器 <script> 双通道）=====================',
  'const RocoCore = {',
  EXPORTS.map(n => '  ' + n + ',').join('\n'),
  '};',
  "if (typeof module !== 'undefined' && module.exports) module.exports = RocoCore;",
  "if (typeof window !== 'undefined') window.RocoCore = RocoCore;",
  '',
].join('\n');

const code = header + body + footer;

// ---------------------------------------------------------------------------
// 4. 自检（符号 + vm 加载 + 真实数据跑通）
// ---------------------------------------------------------------------------
const missing = REQUIRED_SYMBOLS.filter(sym => !new RegExp('(?:function|const|let|var)\\s+' + sym + '\\b').test(code));
if (missing.length) fail('生成文件缺少符号：' + missing.join(', '));

const sandbox = { module: { exports: {} }, console, Math, JSON, Object, Array, Number, String, Map, Set, isNaN, parseInt, parseFloat, RegExp, Boolean };
sandbox.globalThis = sandbox;
let core;
try {
  vm.createContext(sandbox);
  vm.runInContext(code, sandbox, { filename: 'calc-core.js' });
  core = sandbox.module.exports;
} catch (e) {
  fail('vm 加载失败：' + (e && e.stack ? e.stack : e));
}
if (!core || typeof core.computeFinalDamage !== 'function') fail('导出对象没有 computeFinalDamage');

const missingExports = EXPORTS.filter(n => core[n] === undefined);
if (missingExports.length) fail('导出缺失：' + missingExports.join(', '));

// 用真实数据跑一次：龙息帕尔（最高威力攻击技能）→ 贝古斯（档①）
const readJson = n => JSON.parse(fs.readFileSync(path.join(DATA_DIR, n), 'utf8'));
const sprites = readJson('sprites.json');
const skills = readJson('skills.json');
const types = readJson('types.json');
const others = readJson('others.json');
core.bindData({ sprites, skills, types, others });

const atkSprite = sprites['龙息帕尔'];
if (!atkSprite) fail('数据里找不到测试精灵「龙息帕尔」');
const atkSkillId = (atkSprite.skills || [])
  .map(sid => skills[sid])
  .filter(s => s && s.category === '攻击')
  .sort((a, b) => (b.power || 0) - (a.power || 0))[0].id;
const defSprite = sprites['贝古斯'] || sprites[Object.keys(sprites)[0]];

const res = core.computeFinalDamage({
  attacker: atkSprite,
  attackSkill: skills[atkSkillId],
  defender: defSprite,
  defenseSkill: { id: '__none__', name: '无', reduction: 1 },
  starLayer: 3,
  attackerNature: { up: 'spd', down: 'hp' },
  defenderNature: { up: 'hp', down: 'atk' },
  attackerIVs: ['atk', 'matk', 'spd'],
  defenderIVs: ['hp', 'def', 'mdef'],
  attackerBuff: { atk: 0, matk: 0 },
  defenderBuff: { def: 0, mdef: 0 },
  attackerPowerBoost: 0,
  attackerCombo: 0,
});
if (!res || !Number.isFinite(res.finalDamage) || res.finalDamage <= 0) {
  fail('示例计算没有产出有限正数伤害：' + JSON.stringify(res && res.finalDamage));
}

// ---------------------------------------------------------------------------
// 5. 落盘
// ---------------------------------------------------------------------------
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, code, 'utf8');
const kb = (Buffer.byteLength(code, 'utf8') / 1024).toFixed(1);
console.log('[extract-core] ✓ 生成 ' + path.relative(ROOT, OUT) + '（' + kb + ' KB，' + code.split('\n').length + ' 行）');
console.log('[extract-core]   抽样：' + atkSprite.name + ' · ' + skills[atkSkillId].name + ' → ' + defSprite.name +
  '  n=3 伤害 ' + res.finalDamage + '（技能 ' + res.skillDmg + ' + 星陨 ' + res.starDmg + '），防御方 HP ' + res.defHP);
console.log('[extract-core]   符号齐全、vm 加载通过、示例计算通过');
