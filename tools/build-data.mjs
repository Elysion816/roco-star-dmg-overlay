#!/usr/bin/env node
/**
 * tools/build-data.mjs
 * ---------------------------------------------------------------------------
 * 把 _intermediates/upstream/datas/final/*.json 内联打包成渲染层可直接 <script> 加载的
 * src/data/roco-data.js：
 *     window.__ROCO_DATA__ = { sprites, skills, types, others };
 *
 * 这样做的好处：离线首启即有完整图鉴，无需 file:// 下的 fetch（会被 CORS 拦），
 * 也不依赖任何本地 http 服务。运行时若主进程从 stardmg.top 拉到新数据，
 * 渲染层会用它整体替换这份内置包。
 *
 * 运行：node tools/build-data.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import crypto from 'node:crypto';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = path.join(ROOT, '_intermediates', 'upstream', 'datas', 'final');
const OUT = path.join(ROOT, 'src', 'data', 'roco-data.js');

const FILES = ['sprites', 'skills', 'types', 'others'];

function fail(msg) {
  console.error('[build-data] ✗ ' + msg);
  process.exit(1);
}

const data = {};
const stats = [];
for (const name of FILES) {
  const p = path.join(SRC_DIR, name + '.json');
  if (!fs.existsSync(p)) fail('缺少数据文件：' + p);
  const raw = fs.readFileSync(p, 'utf8');
  let obj;
  try {
    obj = JSON.parse(raw);
  } catch (e) {
    fail(name + '.json 不是合法 JSON：' + e.message);
  }
  data[name] = obj;
  stats.push({ name, bytes: Buffer.byteLength(raw, 'utf8'), count: Object.keys(obj).length, sha: crypto.createHash('sha256').update(raw).digest('hex').slice(0, 12) });
}

// 最低限度自检：与 spec 约定的结构一致
const spriteIds = Object.keys(data.sprites);
if (spriteIds.length < 100) fail('sprites.json 数量异常：' + spriteIds.length);
if (!Object.keys(data.skills).length) fail('skills.json 为空');
if (Object.keys(data.types).length < 18) fail('types.json 系别不足 18：' + Object.keys(data.types).length);
for (const id of spriteIds.slice(0, 50)) {
  const s = data.sprites[id];
  if (!s || !s.name || typeof s.hp !== 'number' || !Array.isArray(s.types)) fail('精灵结构异常：' + id);
}

const payload = JSON.stringify(data);
const header = [
  '// ===========================================================================',
  '// src/data/roco-data.js  ——  自动生成，请勿手改',
  '// generated by tools/build-data.mjs from _intermediates/upstream/datas/final/*.json',
  '// ' + stats.map(s => s.name + '.json ' + (s.bytes / 1024).toFixed(1) + 'KB/' + s.count + ' 条(' + s.sha + ')').join('  ·  '),
  '// ===========================================================================',
  '',
].join('\n');

const code = header +
  '(function () {\n' +
  '  var DATA = ' + payload + ';\n' +
  "  if (typeof window !== 'undefined') window.__ROCO_DATA__ = DATA;\n" +
  "  if (typeof module !== 'undefined' && module.exports) module.exports = DATA;\n" +
  '})();\n';

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, code, 'utf8');
console.log('[build-data] ✓ 生成 ' + path.relative(ROOT, OUT) + '（' + (Buffer.byteLength(code, 'utf8') / 1024 / 1024).toFixed(2) + ' MB）');
for (const s of stats) console.log('[build-data]   ' + s.name.padEnd(8) + s.count + ' 条  ' + (s.bytes / 1024).toFixed(1) + ' KB');
